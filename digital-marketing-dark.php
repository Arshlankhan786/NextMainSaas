document.addEventListener("DOMContentLoaded", () => {
    // 1. Initialize Lenis Smooth Scroll
    // Use prefers-reduced-motion to conditionally enable
    const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    
    let lenis;
    if (!prefersReducedMotion) {
        lenis = new Lenis({
            duration: 1.2,
            easing: (t) => Math.min(1, 1.001 - Math.pow(2, -10 * t)),
            direction: 'vertical',
            gestureDirection: 'vertical',
            smooth: true,
            mouseMultiplier: 1,
            smoothTouch: false,
            touchMultiplier: 2,
        });

        function raf(time) {
            lenis.raf(time);
            requestAnimationFrame(raf);
        }
        requestAnimationFrame(raf);
    }

    // 2. Initialize GSAP ScrollTrigger
    gsap.registerPlugin(ScrollTrigger);

    if (!prefersReducedMotion) {
        // Integrate Lenis with ScrollTrigger
        lenis.on('scroll', ScrollTrigger.update);
        gsap.ticker.add((time) => {
            lenis.raf(time * 1000);
        });
        gsap.ticker.lagSmoothing(0);

        // General Fade/Up Reveals
        gsap.utils.toArray('.gs-reveal').forEach(el => {
            gsap.fromTo(el, 
                { opacity: 0, y: 50 },
                {
                    opacity: 1, y: 0,
                    duration: 1,
                    ease: "power3.out",
                    scrollTrigger: {
                        trigger: el,
                        start: "top 85%",
                        toggleActions: "play none none none"
                    }
                }
            );
        });

        // Typography Reveal Effect
        gsap.utils.toArray('.gs-typo').forEach(el => {
            gsap.fromTo(el,
                { color: "var(--dm-border)", filter: "blur(4px)" },
                {
                    color: el.style.color || "var(--dm-text)",
                    filter: "blur(0px)",
                    scrollTrigger: {
                        trigger: el,
                        start: "top 70%",
                        end: "top 40%",
                        scrub: 1
                    }
                }
            );
        });
        
        // Enhance Sticky Cards (Scale down effect as they stack)
        const cards = gsap.utils.toArray('.gs-card');
        cards.forEach((card, i) => {
            if (i !== cards.length - 1) { // Skip last card
                gsap.to(card, {
                    scale: 0.95,
                    opacity: 0.5,
                    scrollTrigger: {
                        trigger: card,
                        start: "top 15%", // When it becomes sticky
                        endTrigger: cards[i + 1],
                        end: "top 25%", // When the next card comes up
                        scrub: true,
                    }
                });
            }
        });
    }

    // 3. FAQ Accordion
    const faqBtns = document.querySelectorAll('.dm-faq__q');
    faqBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            const item = btn.closest('.dm-faq__item');
            const answer = item.querySelector('.dm-faq__a');
            
            // Close others
            document.querySelectorAll('.dm-faq__item').forEach(otherItem => {
                if(otherItem !== item) {
                    otherItem.classList.remove('active');
                    otherItem.querySelector('.dm-faq__a').style.maxHeight = null;
                }
            });
            
            // Toggle current
            item.classList.toggle('active');
            if (item.classList.contains('active')) {
                answer.style.maxHeight = answer.scrollHeight + "px";
            } else {
                answer.style.maxHeight = null;
            }
        });
    });
});
