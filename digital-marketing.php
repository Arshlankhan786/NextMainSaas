<script>
document.addEventListener("DOMContentLoaded", () => {
    const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

    /* ─── LENIS SMOOTH SCROLL ─── */
    let lenis;
    if (!prefersReducedMotion) {
        lenis = new Lenis({
            duration: 1.2,
            easing: (t) => Math.min(1, 1.001 - Math.pow(2, -10 * t)),
            direction: 'vertical',
            gestureDirection: 'vertical',
            smooth: true,
            mouseMultiplier: 1,
            smoothTouch: false,
            touchMultiplier: 2,
        });
        function raf(time) {
            lenis.raf(time);
            requestAnimationFrame(raf);
        }
        requestAnimationFrame(raf);
    }

    /* ─── GSAP + SCROLLTRIGGER ─── */
    gsap.registerPlugin(ScrollTrigger);

    if (!prefersReducedMotion) {
        // Integrate Lenis with ScrollTrigger
        if (lenis) {
            lenis.on('scroll', ScrollTrigger.update);
            gsap.ticker.add((time) => { lenis.raf(time * 1000); });
            gsap.ticker.lagSmoothing(0);
        }

        /* ─── GENERAL REVEALS ─── */
        gsap.utils.toArray('.gs-reveal').forEach(el => {
            gsap.to(el, {
                opacity: 1, y: 0,
                duration: 0.9,
                ease: "power3.out",
                scrollTrigger: {
                    trigger: el,
                    start: "top 88%",
                    toggleActions: "play none none none"
                }
            });
        });

        gsap.utils.toArray('.gs-reveal-left').forEach(el => {
            gsap.to(el, {
                opacity: 1, x: 0,
                duration: 1,
                ease: "power3.out",
                scrollTrigger: {
                    trigger: el,
                    start: "top 85%",
                    toggleActions: "play none none none"
                }
            });
        });

        gsap.utils.toArray('.gs-reveal-right').forEach(el => {
            gsap.to(el, {
                opacity: 1, x: 0,
                duration: 1,
                ease: "power3.out",
                scrollTrigger: {
                    trigger: el,
                    start: "top 85%",
                    toggleActions: "play none none none"
                }
            });
        });

        gsap.utils.toArray('.gs-reveal-scale').forEach(el => {
            gsap.to(el, {
                opacity: 1, scale: 1,
                duration: 1.1,
                ease: "power3.out",
                scrollTrigger: {
                    trigger: el,
                    start: "top 85%",
                    toggleActions: "play none none none"
                }
            });
        });

        /* ─── STAGGER GROUPS ─── */
        // Group stagger elements by their parent section
        const sections = document.querySelectorAll('.dm-section, .dm-hero');
        sections.forEach(section => {
            const staggerEls = section.querySelectorAll('.gs-stagger');
            if (staggerEls.length > 0) {
                gsap.to(staggerEls, {
                    opacity: 1, y: 0,
                    duration: 0.7,
                    ease: "power3.out",
                    stagger: 0.08,
                    scrollTrigger: {
                        trigger: section,
                        start: "top 75%",
                        toggleActions: "play none none none"
                    }
                });
            }
        });

        /* ─── STICKY CARDS (SKILLS SECTION — ONLY STICKY) ─── */
        const cards = gsap.utils.toArray('.gs-card');
        cards.forEach((card, i) => {
            if (i !== cards.length - 1) {
                gsap.to(card, {
                    scale: 0.95,
                    opacity: 0.5,
                    filter: "brightness(0.95)",
                    scrollTrigger: {
                        trigger: card,
                        start: "top 12%",
                        endTrigger: cards[i + 1],
                        end: "top 20%",
                        scrub: true,
                    }
                });
            }
        });

        /* ─── PROJECT DEVICE PARALLAX ─── */
        gsap.utils.toArray('.dm-project__device').forEach(device => {
            gsap.fromTo(device, 
                { y: 30 },
                {
                    y: -20,
                    ease: "none",
                    scrollTrigger: {
                        trigger: device,
                        start: "top bottom",
                        end: "bottom top",
                        scrub: 1.5,
                    }
                }
            );
        });

        /* ─── AI CENTER PULSE ─── */
        const aiCenter = document.querySelector('.dm-ai__center');
        if (aiCenter) {
            gsap.to(aiCenter, {
                boxShadow: "0 12px 60px rgba(124, 58, 237, 0.5)",
                scale: 1.05,
                duration: 1.5,
                yoyo: true,
                repeat: -1,
                ease: "sine.inOut"
            });
        }

        /* ─── TIMELINE STEP CONNECTORS ─── */
        gsap.utils.toArray('.dm-timeline__step').forEach(step => {
            gsap.fromTo(step.querySelector('.dm-timeline__marker'),
                { scale: 0.5, opacity: 0 },
                {
                    scale: 1, opacity: 1,
                    duration: 0.5,
                    ease: "back.out(1.7)",
                    scrollTrigger: {
                        trigger: step,
                        start: "top 80%",
                        toggleActions: "play none none none"
                    }
                }
            );
        });
    }

    /* ─── FAQ ACCORDION ─── */
    const faqBtns = document.querySelectorAll('.dm-faq__q');
    faqBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            const item = btn.closest('.dm-faq__item');
            const answer = item.querySelector('.dm-faq__a');
            // Close others
            document.querySelectorAll('.dm-faq__item').forEach(otherItem => {
                if (otherItem !== item) {
                    otherItem.classList.remove('active');
                    otherItem.querySelector('.dm-faq__a').style.maxHeight = null;
                }
            });
            // Toggle current
            item.classList.toggle('active');
            if (item.classList.contains('active')) {
                answer.style.maxHeight = answer.scrollHeight + "px";
            } else {
                answer.style.maxHeight = null;
            }
        });
    });

    /* ─── SMOOTH SCROLL FOR ANCHOR LINKS ─── */
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function(e) {
            const target = document.querySelector(this.getAttribute('href'));
            if (target) {
                e.preventDefault();
                if (lenis) {
                    lenis.scrollTo(target, { offset: -60 });
                } else {
                    target.scrollIntoView({ behavior: 'smooth', block: 'start' });
                }
            }
        });
    });
});
